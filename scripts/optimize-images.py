#!/usr/bin/env python3
"""Downscale oversized photographs in static/img/ and strip their metadata, in place.

Doc pages display photos at most ~900 CSS px wide (~1800 device px on a 2x
screen), but a few phone photos were committed at 4080x3060. This shrinks any
raster image whose longer side exceeds MAX_SIDE, keeping its path and format,
so no URL changes and no Markdown needs editing.

It also strips EXIF from every photo, resized or not. Phone and camera photos
carry the device model and capture time (sometimes GPS), which a pseudonymous
publisher should not ship.

Skipped on purpose:
- static/img/og/ and static/img/social-card.png: generated, fixed 1200x630.
- static/img/diagrams/: SVG.
- favicons: generated by scripts/generate-favicons.py at exact sizes.

Run it after adding photos:  python3 scripts/optimize-images.py
Dry run (report only):       python3 scripts/optimize-images.py --check
--check exits 1 if any photo is oversized or still carries EXIF, so it can gate CI.
"""

import sys
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent / "static" / "img"
MAX_SIDE = 1800
WEBP_QUALITY = 82
SKIP_DIRS = {"og", "diagrams"}
SKIP_FILES = {"social-card.png", "favicon.ico"}
EXTS = {".webp", ".png", ".jpg", ".jpeg"}


def candidates():
    for path in sorted(ROOT.rglob("*")):
        if path.suffix.lower() not in EXTS or path.name in SKIP_FILES:
            continue
        if SKIP_DIRS.intersection(path.relative_to(ROOT).parts[:-1]):
            continue
        yield path


def main() -> int:
    check_only = "--check" in sys.argv
    oversized = 0
    stripped = 0
    saved = 0
    for path in candidates():
        with Image.open(path) as im:
            w, h = im.size
            too_big = max(w, h) > MAX_SIDE
            has_exif = len(im.getexif()) > 0
            if not too_big and not has_exif:
                continue
            rel = path.relative_to(ROOT.parent.parent)
            oversized += too_big
            stripped += has_exif
            if check_only:
                print(f"{'oversized' if too_big else 'has EXIF'}: {rel} {w}x{h}")
                continue
            before = path.stat().st_size
            # Apply EXIF rotation first, then save without any EXIF block.
            out = ImageOps.exif_transpose(im)
            if too_big:
                out.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
            fmt = (im.format or path.suffix.lstrip(".")).upper()
        if fmt == "WEBP":
            # A metadata-only rewrite re-encodes too, so keep quality high there.
            out.save(path, "WEBP", quality=WEBP_QUALITY if too_big else 92, method=6)
        elif fmt in ("JPEG", "JPG"):
            out.convert("RGB").save(path, "JPEG", quality=85, optimize=True, progressive=True)
        else:
            out.save(path, optimize=True)
        after = path.stat().st_size
        saved += before - after
        print(f"rewrote {rel}: {w}x{h} -> {out.size[0]}x{out.size[1]}, "
              f"{before // 1024} KB -> {after // 1024} KB")
    if check_only:
        return 1 if (oversized or stripped) else 0
    print(f"{oversized} resized, {stripped} stripped of EXIF, {saved // 1024} KB saved")
    return 0


if __name__ == "__main__":
    sys.exit(main())
