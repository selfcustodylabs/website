/**
 * Security policy for the site, defined once.
 *
 * Two consumers:
 * - docusaurus.config.js emits a meta Content-Security-Policy, which is all
 *   GitHub Pages can do. A meta CSP cannot carry frame-ancestors, so that
 *   directive is header-only.
 * - plugins/cloudflare writes the same policy, plus the headers a meta tag
 *   cannot set, into build/_headers for Cloudflare Pages.
 *
 * When both are present the browser enforces both, so a host allowed here must
 * be allowed in the meta policy too or it stays blocked. Keeping one definition
 * is what stops the two from drifting.
 *
 * Third parties allowed, and why:
 * - static.cloudflareinsights.com / cloudflareinsights.com: Cloudflare Web
 *   Analytics, the cookieless analytics enabled in the Pages dashboard after the
 *   move to Cloudflare. Nothing else on the site loads from another domain.
 */

const CSP = {
  "default-src": ["'self'"],
  // 'unsafe-inline': Docusaurus inlines its color-mode and announcement-bar
  // scripts in <head>. No 'unsafe-eval' anywhere.
  "script-src": ["'self'", "'unsafe-inline'", "https://static.cloudflareinsights.com"],
  "style-src": ["'self'", "'unsafe-inline'"],
  "img-src": ["'self'", "data:"],
  "font-src": ["'self'"],
  "connect-src": ["'self'", "https://cloudflareinsights.com"],
  "object-src": ["'none'"],
  "base-uri": ["'self'"],
  "form-action": ["'self'"],
  "frame-ancestors": ["'none'"],
};

/** Directives a browser ignores when the policy arrives in a <meta> tag. */
const HEADER_ONLY = new Set(["frame-ancestors"]);

/**
 * @param {{forMeta?: boolean}} [options]
 * @returns {string} the policy as a header value
 */
export function contentSecurityPolicy({ forMeta = false } = {}) {
  return Object.entries(CSP)
    .filter(([name]) => !(forMeta && HEADER_ONLY.has(name)))
    .map(([name, values]) => [name, ...values].join(" "))
    .join("; ");
}

const SITE = "https://selfcustodylabs.com";

/**
 * Contents of build/_headers for Cloudflare Pages.
 *
 * - Hashed build assets never change under the same URL, so they can be cached
 *   for a year. HTML keeps Cloudflare's default (revalidate every request).
 * - The favicon set and the IndexNow key keep default caching on purpose: their
 *   URLs are stable forever and their bytes are overwritten in place.
 * - nostr.json needs CORS for NIP-05 verification in web clients. GitHub Pages
 *   sent Access-Control-Allow-Origin on everything; Cloudflare does not.
 * - Each Markdown mirror points search engines at its HTML page as canonical,
 *   so the mirror stays readable for agents without competing in the index.
 * - The *.pages.dev hostnames are duplicate copies of the site and must never be
 *   indexed.
 *
 * @returns {string}
 */
export function cloudflareHeadersFile() {
  return `# Generated by plugins/cloudflare from src/data/securityHeaders.js. Do not edit.
/*
  Content-Security-Policy: ${contentSecurityPolicy()}
  Strict-Transport-Security: max-age=31536000
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/.well-known/nostr.json
  Access-Control-Allow-Origin: *
  Content-Type: application/json; charset=utf-8

/*.md
  Content-Type: text/markdown; charset=utf-8
  Link: <${SITE}/:splat/>; rel="canonical"

/llms.txt
  Content-Type: text/plain; charset=utf-8

/llms-full.txt
  Content-Type: text/plain; charset=utf-8

https://:project.pages.dev/*
  X-Robots-Tag: noindex

https://:version.:project.pages.dev/*
  X-Robots-Tag: noindex
`;
}
