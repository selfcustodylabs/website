/**
 * cloudflare: real 301s and real response headers for Cloudflare Pages.
 *
 * GitHub Pages can only answer an old URL with a meta-refresh page that returns
 * HTTP 200, which is why retired URLs scattered across Search Console buckets.
 * Cloudflare Pages reads two plain-text files from the build output:
 *
 *   build/_redirects   one "from to 301" line per retired URL
 *   build/_headers     CSP, HSTS, caching and the rest (src/data/securityHeaders.js)
 *
 * On Cloudflare a `_redirects` rule wins even when a static file exists at the
 * same path, so the meta-refresh pages that plugin-client-redirects still writes
 * (for GitHub Pages, during the rollback window) are never served there.
 *
 * The redirect list is the same one plugin-client-redirects consumes
 * (src/data/redirects.js), expanded here against the built routes. The build
 * fails rather than ship a broken rule: a target that is not a route, a source
 * that would shadow a live page, a chain, or two targets for one source.
 *
 * @module plugins/cloudflare
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";

import { redirects, createRedirects } from "../../src/data/redirects.js";
import { cloudflareHeadersFile } from "../../src/data/securityHeaders.js";

/** Cloudflare Pages accepts at most 2,000 static redirect rules. */
const MAX_STATIC_REDIRECTS = 2000;

const withSlash = (p) => (p.endsWith("/") ? p : `${p}/`);
const noSlash = (p) => (p.length > 1 ? p.replace(/\/+$/, "") : p);

/**
 * Expand the redirect list into from -> to pairs, normalised.
 *
 * @param {string[]} routesPaths - every route of the built site
 * @returns {Map<string, string>} source without trailing slash -> target with one
 */
export function buildRedirectMap(routesPaths) {
  const map = new Map();
  const errors = [];

  const add = (from, to) => {
    const key = noSlash(from);
    const target = withSlash(to);
    const existing = map.get(key);
    if (existing && existing !== target) {
      errors.push(`two targets for ${key}: ${existing} and ${target}`);
      return;
    }
    map.set(key, target);
  };

  for (const { from, to } of redirects) {
    for (const f of [].concat(from)) add(f, to);
  }
  for (const route of routesPaths) {
    const froms = createRedirects(route);
    if (froms) for (const f of [].concat(froms)) add(f, route);
  }

  const routes = new Set(routesPaths.map(withSlash));
  for (const [from, to] of map) {
    if (!routes.has(to)) errors.push(`dead target: ${from} -> ${to}`);
    if (routes.has(withSlash(from))) errors.push(`source is a live page: ${from}`);
    if (map.has(noSlash(to))) errors.push(`chain: ${from} -> ${to} -> ${map.get(noSlash(to))}`);
  }
  if (errors.length > 0) {
    throw new Error(`[cloudflare] invalid redirects:\n  ${errors.join("\n  ")}`);
  }
  return map;
}

export default function cloudflarePlugin() {
  return {
    name: "cloudflare-pages",

    async postBuild({ routesPaths, outDir }) {
      const map = buildRedirectMap(routesPaths);

      // Cloudflare matches the path exactly, so each source is listed with and
      // without its trailing slash.
      const lines = [];
      for (const [from, to] of [...map].sort(([a], [b]) => a.localeCompare(b))) {
        lines.push(`${from} ${to} 301`, `${withSlash(from)} ${to} 301`);
      }
      if (lines.length > MAX_STATIC_REDIRECTS) {
        throw new Error(
          `[cloudflare] ${lines.length} redirect rules exceed Cloudflare's limit of ${MAX_STATIC_REDIRECTS}`,
        );
      }

      writeFileSync(
        join(outDir, "_redirects"),
        "# Generated by plugins/cloudflare from src/data/redirects.js. Do not edit.\n" +
          `${lines.join("\n")}\n`,
      );
      writeFileSync(join(outDir, "_headers"), cloudflareHeadersFile());
      console.log(`[cloudflare] wrote _redirects (${map.size} sources, ${lines.length} rules) and _headers`);
    },
  };
}
